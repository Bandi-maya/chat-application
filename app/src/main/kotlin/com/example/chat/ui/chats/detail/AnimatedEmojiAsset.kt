    /** Port of ChatyEmojiRegistry.normalize (emoji_registry.dart:87-91). */
    fun normalize(emoji: String): String =
        if (emoji.isEmpty()) emoji
        else emoji.replace("\uFE0F", "").replace("\uFE0E", "").trim()

    /** Port of ChatyEmojiRegistry.find: direct hit, then normalized hit. */
    fun findNotoId(unicode: String): String? {
        idByUnicode[unicode]?.let { return it }
        return idByUnicode[normalize(unicode)]
    }

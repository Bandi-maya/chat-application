    fun drawable(theme: ChatyIconThemeId, icon: ChatyIconId, selected: Boolean = false): Int? =
        ChatySupplementalIcons.drawable(theme, icon) ?:
        if (selected && theme == ChatyIconThemeId.phosphorRegular)
            selectedPhosphorGlyphs[icon] ?: glyphs[theme]?.get(icon)
        else if (selected && theme == ChatyIconThemeId.majesticonsLine)
            glyphs[ChatyIconThemeId.majesticonsSolid]?.get(icon) ?: glyphs[theme]?.get(icon)
        else if (selected && theme == ChatyIconThemeId.pikaiconsStroke)
            glyphs[ChatyIconThemeId.pikaiconsSolid]?.get(icon) ?: glyphs[theme]?.get(icon)
        else glyphs[theme]?.get(icon)
    fun hasPreview(theme: ChatyIconThemeId): Boolean =
        drawable(theme, ChatyIconId.chats) != null && drawable(theme, ChatyIconId.settings) != null

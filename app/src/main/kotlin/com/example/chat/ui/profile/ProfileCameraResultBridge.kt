package com.example.chat.ui.profile

import android.content.Context
import androidx.activity.ComponentActivity
import androidx.activity.result.ActivityResultLauncher
import androidx.activity.result.contract.ActivityResultContracts
import androidx.core.content.FileProvider
import java.io.File
import java.util.UUID
import kotlinx.coroutines.CompletableDeferred

/** Stable activity registry route, independent of editor composition. No upload or account data.
 * MainActivity must register before setContent on every creation. One pending writer at a time. */
object ProfileCameraResultBridge {
    private var launcher: ActivityResultLauncher<android.net.Uri>? = null
    private var owner: ProfileCameraTerminalOwner? = null
    private var waiter: CompletableDeferred<File?>? = null
    private var context: Context? = null
    private var registeredActivity: ComponentActivity? = null
    private const val KEY = "chaty.profile.camera.terminal.v1"

    fun register(activity: ComponentActivity) {
        try { registerReady(activity) }
        catch (error: Exception) { ProfileLocalOutputs.markBlocked(error) }
    }
    private fun registerReady(activity: ComponentActivity) {
        val app = activity.applicationContext
        ProfileLocalOutputs.initialize(app)
        context = app
        registeredActivity = activity
        activity.lifecycle.addObserver(object : androidx.lifecycle.DefaultLifecycleObserver {
            override fun onDestroy(owner: androidx.lifecycle.LifecycleOwner) {
                if (registeredActivity === activity) { launcher = null; registeredActivity = null }
                // Do not unregister pending stable registry key; restoration owns late result.
            }
        })
        if (owner == null) {
            val prefs = app.getSharedPreferences("profile_camera_terminal", Context.MODE_PRIVATE)
            val directory = File(app.cacheDir, "profile_camera_terminal").apply { mkdirs() }
            // Only accept a leaf generated by this route. Never delete an arbitrary persisted path.
            val restored = prefs.getString("leaf", null)?.takeIf {
                it.matches(Regex("capture_[a-f0-9-]+\\.jpg"))
            }?.let { File(directory, it).absolutePath }
            owner = ProfileCameraTerminalOwner(
                save = { path, terminal ->
                    check(prefs.edit().apply { if (path == null) remove("leaf").remove("terminal") else putString("leaf", File(path).name).putBoolean("terminal", terminal) }.commit()) {
                        "Could not save profile camera ownership."
                    }
                },
                delete = { val f = File(it); !f.exists() || f.delete() },
                restoredPath = restored,
                restoredTerminal = prefs.getBoolean("terminal", false),
            )
        }
        // Retry only cleanup already authorized by a terminal callback, never an active writer.
        runCatching { owner?.retryTerminalCleanup() }
        // Direct registry registration is not owned by a disappearing Composable. Stable key
        // lets the restored Activity registry route its terminal result to this same owner.
        launcher = activity.activityResultRegistry.register(KEY, ActivityResultContracts.TakePicture()) { ok ->
            val pending = waiter
            waiter = null
            try {
                if (pending == null) owner?.retire()
                val path = owner?.complete(ok)
                val file = path?.let(::File)
                if (file != null) {
                    // Persist local ownership BEFORE clearing the terminal record or completing waiter.
                    ProfileLocalOutputs.record(file)
                    owner?.acknowledgeLocalHandoff(file.absolutePath)
                }
                if (pending == null || !pending.complete(file)) {
                    // Terminal external writer is done. Keep deletion failures visible.
                    if (file != null) ProfileLocalOutputs.delete(file)
                }
            } catch (error: Exception) {
                // Owner retains its persistent cleanup tombstone on delete/clear failure.
                ProfileLocalOutputs.markBlocked(error)
                // Complete can leave a durable terminal tombstone if local journal recording
                // failed. Retry only that known-terminal cleanup, never an active writer.
                runCatching { owner?.retire(); owner?.retryTerminalCleanup() }
                    .onFailure { if (it is Exception) ProfileLocalOutputs.markBlocked(it) }
                pending?.completeExceptionally(error)
            } finally {
                if (pending != null && !pending.isCompleted) pending.complete(null)
            }
        }
    }

    @OptIn(kotlinx.coroutines.ExperimentalCoroutinesApi::class)
    suspend fun pick(): File? {
        check(android.os.Looper.myLooper() == android.os.Looper.getMainLooper())
        ProfileLocalOutputs.requireReady()
        val app = context ?: error("Profile camera activity owner is not registered.")
        val activeLauncher = launcher ?: error("Profile camera activity owner is not registered.")
        val terminal = owner ?: error("Profile camera activity owner is not registered.")
        check(waiter == null && !terminal.hasPending()) { "Previous camera result is still pending." }
        val file = File(File(app.cacheDir, "profile_camera_terminal"), "capture_${UUID.randomUUID()}.jpg")
        val pending = CompletableDeferred<File?>()
        terminal.begin(file.absolutePath)
        waiter = pending
        try {
            val uri = FileProvider.getUriForFile(app, app.packageName + ".fileprovider", file)
            activeLauncher.launch(uri)
        } catch (error: Exception) {
            waiter = null
            terminal.launchFailed()
            throw error
        }
        try {
            return pending.await()
        } catch (cancelled: kotlinx.coroutines.CancellationException) {
            terminal.retire()
            // A result can have arrived just before cancellation at the suspension handback.
            if (pending.isCompleted && !pending.isCancelled) runCatching { pending.getCompleted()?.let { ProfileLocalOutputs.delete(it) } }
                .onFailure { if (it is Exception) ProfileLocalOutputs.markBlocked(it) }
            throw cancelled
        } finally {
            if (waiter === pending) { waiter = null; terminal.retire() }
        }
    }
}

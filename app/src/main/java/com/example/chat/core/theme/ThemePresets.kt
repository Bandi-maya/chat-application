    /** Overridable platform-brightness probe (the Compose shell installs the
     *  real one from Configuration.uiMode); true = light. Defaults to light
     *  so JVM tests are deterministic. */
    var platformIsLightProvider: () -> Boolean = { true }

    fun getSystemDefaultTheme(platformIsLight: Boolean? = null): ThemeConfig {
        val light = platformIsLight ?: platformIsLightProvider()
        return if (light) warmNeutral else warmNeutralDark
    }

    fun getById(id: String): ThemeConfig =
        all.firstOrNull { it.id == id } ?: monochromeDark
}
